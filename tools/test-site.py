import os
import asyncio,json
from playwright.async_api import async_playwright
U='http://localhost:8765/'
R=[]
def ok(name,cond,extra=''): R.append(('PASS' if cond else 'FAIL',name,extra))
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(args=['--no-sandbox'],**({'executable_path':os.environ['CHROME_PATH']} if os.environ.get('CHROME_PATH') else {}))
        ctx=await b.new_context(viewport={'width':1440,'height':900})
        pg=await ctx.new_page();errs=[]
        pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.add_init_script("window.__acCount=0;const A=window.AudioContext;window.AudioContext=function(){window.__acCount++;return new A()};")
        await pg.goto(U,wait_until='networkidle')
        ok('gate visible on first visit',await pg.is_visible('#gate'))
        ok('sound off by default',await pg.get_attribute('#sound','aria-pressed')=='false')
        ok('focus starts on board button',await pg.evaluate("document.activeElement.id")=='board')
        for _ in range(5): await pg.keyboard.press('Tab')
        ok('focus trapped in gate',await pg.evaluate("!!document.activeElement.closest('#gate')"))
        await pg.click('#board');await pg.wait_for_timeout(4800)
        ok('quiet boarding removes gate',await pg.evaluate("!document.getElementById('gate')"))
        ok('no audio created when boarding quietly',await pg.evaluate("window.__acCount")==0)
        await pg.reload(wait_until='networkidle')
        ok('gate skipped for rest of session',not await pg.is_visible('#gate'))
        # builder
        await pg.goto(U+'?skip#build',wait_until='networkidle');await pg.wait_for_timeout(500)
        await pg.click('.brow[data-i="2"] button[data-v="250"]');await pg.click('.brow[data-i="5"] button[data-v="500"]')
        await pg.wait_for_timeout(700)
        ok('builder total $750',(await pg.text_content('#total'))=='$750',await pg.text_content('#total'))
        ok('titles are per program, no ladder',await pg.evaluate("[...document.querySelectorAll('#tclass li')].length")==2 and not await pg.evaluate("!!document.getElementById('unlock')"))
        await pg.click('button[data-go="2"]');await pg.wait_for_timeout(500)
        ok('programs of interest auto-checked',await pg.evaluate("[...document.querySelectorAll('input[name=programs]:checked')].map(x=>x.value).join('|')")=='BRIDGE to Medicine|BRIDGE to Policy & Law')
        ok('range auto-set',await pg.input_value('#fRange')=='$250 to $999')
        await pg.click('fieldset[data-step="2"] button[data-go="3"]');await pg.wait_for_timeout(300)
        ok('validation blocks review',await pg.is_visible('#ferr') and not await pg.is_visible('fieldset[data-step="3"]'),await pg.text_content('#ferr'))
        await pg.fill('#orgName','Test Org');await pg.fill('input[name=name]','Pat Lee');await pg.fill('input[name=email]','pat@bad')
        await pg.click('fieldset[data-step="2"] button[data-go="3"]');await pg.wait_for_timeout(300)
        ok('invalid email caught','valid email' in (await pg.text_content('#ferr')))
        await pg.fill('input[name=email]','pat@example.com');await pg.check('input[name=engagement][value="Mentor students"]',force=True)
        await pg.click('fieldset[data-step="2"] button[data-go="3"]');await pg.wait_for_timeout(600)
        rv=await pg.text_content('#review')
        ok('review summary shows data','Test Org' in rv and 'Mentor students' in rv and '$750' in rv)
        ok('send button honest label',(await pg.text_content('#sendBtn'))=='Send by email')
        await pg.click('#sendBtn');await pg.wait_for_timeout(400)
        ok('email modal opens (no endpoint)',await pg.is_visible('#mailModal'))
        gm=await pg.get_attribute('[data-m=gmail]','href')
        ok('gmail link carries summary','Test%20Org' in gm and 'info%40bridgethedistrict.org' not in gm[:20])
        txt=await pg.evaluate("document.body.innerText")
        ok('no false success message','Received' not in txt and 'reached the BRIDGE team' not in txt)
        await pg.keyboard.press('Escape');await pg.wait_for_timeout(200)
        ok('modal closes on Escape',not await pg.is_visible('#mailModal'))
        # proposal page
        pp=await ctx.new_page();await pp.goto(U+'prospectus.html?proposal=1',wait_until='networkidle')
        t=await pp.evaluate("document.body.innerText")
        ok('custom proposal includes org','Prepared for' in t and 'Test Org' in t)
        ok('proposal omits email','pat@example.com' not in t)
        # pathways + toc
        await pg.click('#pw-tech');ok('pathway tab switches',' Proposed opportunity'.strip() in await pg.text_content('.pw-panel'))
        await pg.focus('#toc-t-scholars');await pg.keyboard.press('ArrowRight')
        ok('model keyboard nav',await pg.get_attribute('#toc-t-college','aria-selected')=='true')
        ok('no page errors (index)',not errs,errs)
        # mobile menu
        m=await b.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True);mp=await m.new_page()
        await mp.goto(U+'?skip',wait_until='networkidle');await mp.click('#menuBtn')
        ok('mobile menu opens',await mp.is_visible('#menuPanel'))
        await mp.click('#menuPanel a[href="#impact"]');await mp.wait_for_timeout(2500)
        ok('menu closes and navigates',not await mp.is_visible('#menuPanel') and await mp.evaluate("Math.abs(document.getElementById('impact').getBoundingClientRect().top)<200"))
        for path in ['?skip','express.html','prospectus.html','present.html']:
            await mp.goto(U+path,wait_until='networkidle')
            ok('no horizontal scroll 390px '+path,await mp.evaluate("document.documentElement.scrollWidth<=innerWidth"),await mp.evaluate("document.documentElement.scrollWidth"))
        # express
        ep=await ctx.new_page();ee=[];ep.on('pageerror',lambda e:ee.append(str(e)))
        await ep.goto(U+'express.html',wait_until='networkidle')
        await ep.click('#xform button[type=submit]');ok('express validation',await ep.is_visible('#xerr'))
        await ep.fill('input[name=org]','Acme');await ep.fill('input[name=name]','Jo');await ep.fill('input[name=email]','jo@acme.org')
        await ep.click('#xform button[type=submit]');ok('express review shown',await ep.is_visible('#xreview') and 'Acme' in await ep.text_content('#xsum'))
        await ep.click('#xedit');ok('express edit returns',await ep.input_value('input[name=org]')=='Acme')
        ok('no page errors (express)',not ee,ee)
        # deep link + no-js + reduced motion
        dp=await ctx.new_page();await dp.goto(U+'#pathways',wait_until='networkidle')
        ok('deep link skips gate',not await dp.is_visible('#gate'))
        nj=await b.new_context(java_script_enabled=False);np_=await nj.new_page();await np_.goto(U+'index.html')
        ok('no-JS: gate hidden, content readable',not await np_.is_visible('#gate') and await np_.is_visible('#purpose h2'))
        rm=await b.new_context(reduced_motion='reduce');rp=await rm.new_page();await rp.goto(U,wait_until='networkidle');await rp.click('#board');await rp.wait_for_timeout(300)
        ok('reduced motion: instant boarding',await rp.evaluate("!document.getElementById('gate')"))
        ok('reduced motion: content visible',await rp.evaluate("getComputedStyle(document.querySelector('#impact h2')).opacity")=='1')
        # deck
        dk=await ctx.new_page();await dk.goto(U+'present.html#12',wait_until='networkidle')
        ok('deck deep link to last slide',(await dk.text_content('#dcount'))=='12 / 12')
        await dk.keyboard.press('Home');await dk.wait_for_timeout(1300);ok('deck Home key',(await dk.text_content('#dcount'))=='1 / 12')
        await b.close()
    for r in R: print(*r)
    print(sum(r[0]=='PASS' for r in R),'/',len(R))
asyncio.run(main())
